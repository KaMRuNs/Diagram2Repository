_GO_MAIN = """package main

import (
	"encoding/json"
	"log"
	"net/http"
	"os"
)

// Connection strings injected by docker-compose.yml
var connections = []string{__CONNECTIONS__}

func writeJSON(w http.ResponseWriter, v any) {
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(v)
}

func main() {
	port := os.Getenv("PORT")
	if port == "" {
		port = "__PORT__"
	}

	http.HandleFunc("/health", func(w http.ResponseWriter, r *http.Request) {
		writeJSON(w, map[string]string{"status": "ok", "service": "__ID__"})
	})

	http.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		present := map[string]bool{}
		for _, name := range connections {
			present[name] = os.Getenv(name) != ""
		}
		writeJSON(w, map[string]any{"service": "__LABEL__", "connections": present})
	})

	// TODO: add your handlers here.

	log.Printf("__LABEL__ listening on :%s", port)
	log.Fatal(http.ListenAndServe(":"+port, nil))
}
"""

