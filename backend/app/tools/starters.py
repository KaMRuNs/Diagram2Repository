def _fill(template: str, **tokens: str) -> str:
    for key, value in tokens.items():
        template = template.replace(f"__{key.upper()}__", value)
    return template


def _safe(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9 ._'()-]", "", text)[:60] or "Service"


