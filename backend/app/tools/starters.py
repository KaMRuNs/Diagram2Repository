def starter_files(
    tech: str, node_id: str, label: str, port: int, connections: list[str], talks_to: list[str]
) -> dict[str, str]:
    """Files for services/<node_id>/, keyed by path relative to that folder."""
    tok = {"id": node_id, "label": _safe(label), "port": str(port)}
    talks = ", ".join(talks_to) or "nothing yet"
    if tech == "node":
        pkg = {
            "name": node_id,
            "private": True,
            "type": "module",
            "scripts": {"start": "node src/index.js"},
            "dependencies": {"express": "^4.21.1"},
        }
        return {
            "package.json": json.dumps(pkg, indent=2) + "\n",
            "src/index.js": _fill(_NODE_INDEX, connections=json.dumps(connections), **tok),
            "Dockerfile": _fill(_NODE_DOCKERFILE, **tok),
        }
    if tech == "python":
        return {
            "requirements.txt": "fastapi==0.115.5\nuvicorn[standard]==0.32.1\n",
            "main.py": _fill(_PY_MAIN, connections=json.dumps(connections), **tok),
            "Dockerfile": _fill(_PY_DOCKERFILE, **tok),
        }
    if tech == "go":
        return {
            "go.mod": f"module {node_id.replace('-', '')}\n\ngo 1.23\n",
            "main.go": _fill(_GO_MAIN, connections=", ".join(json.dumps(c) for c in connections), **tok),
            "Dockerfile": _fill(_GO_DOCKERFILE, **tok),
        }
    if tech == "react":
        pkg = {
            "name": node_id,
            "private": True,
            "type": "module",
            "scripts": {"dev": f"vite --host 0.0.0.0 --port {port}", "build": "vite build"},
            "dependencies": {"react": "18.3.1", "react-dom": "18.3.1"},
            "devDependencies": {"vite": "5.4.11", "@vitejs/plugin-react": "4.3.4"},
        }
        return {
            "package.json": json.dumps(pkg, indent=2) + "\n",
            "vite.config.js": _VITE_CONFIG,
            "index.html": _fill(_REACT_INDEX, **tok),
            "src/main.jsx": _REACT_MAIN,
            "src/App.jsx": _fill(_REACT_APP, talks_to=talks, **tok),
            "Dockerfile": _fill(_REACT_DOCKERFILE, **tok),
        }
    if tech == "static":
        return {
            "index.html": _fill(_STATIC_INDEX, talks_to=talks, **tok),
            "Dockerfile": _STATIC_DOCKERFILE,
        }
    raise ValueError(f"no starter for tech '{tech}'")
